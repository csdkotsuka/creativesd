    req = urllib.request.Request(
        api_url,
        headers={"Authorization": f"Basic {encoded_creds}"}
    )
    
    try:
        with urllib.request.urlopen(req) as resp:
            existing_posts = json.loads(resp.read().decode())
    except Exception as e:
        print(f"Error fetching existing draft posts: {e}", file=sys.stderr)
        return

    print(f"Fetched {len(existing_posts)} draft posts from WordPress.")

    # タイトルマッチングで更新
    updated_count = 0
    for post in existing_posts:
        post_id = post["id"]
        post_title = post["title"]["rendered"]

        # 対応する記事データを検索
        matched_art = None
        for art in articles_data:
            if art["title"].strip() == post_title.strip() or art["title"][:20] in post_title:
                matched_art = art
                break

        if not matched_art:
            print(f"Warning: No match found for post ID {post_id} ({post_title[:25]}...)")
            continue

        cat_id = CAT_MAP.get(matched_art["category_name"], 5)
        new_content = build_article_content(matched_art)

